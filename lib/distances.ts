export function findDistance(depart: string, arrivee: string): number | null {
  const normalize = (s: string) => s.trim().toUpperCase()
  const d = normalize(depart)
  const a = normalize(arrivee)
  const found = distances.find(
    r => normalize(r.COMMUNE_DEPART) === d && normalize(r.COMMUNE_ARRIVEE) === a
  ) || distances.find(
    r => normalize(r.COMMUNE_DEPART) === a && normalize(r.COMMUNE_ARRIVEE) === d
  )
  return found?.KM ?? null
}

export function getAllCommunes(): string[] {
  const set = new Set<string>()
  for (const d of distances) {
    set.add(d.COMMUNE_DEPART)
  }
  return Array.from(set).sort()
}

